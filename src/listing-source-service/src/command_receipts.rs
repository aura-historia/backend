use crate::{
    ports::{
        ListingIngestionConfiguration, ListingIngestionConfigurationUpdate,
        ListingSourceIngestionConfigurations, UpdateListingSourceIngestionConfigurations,
    },
    use_cases::commands::{
        create_listing_source::{CreateListingSourceResult, ListingSourceOperator},
        update_listing_source::UpdateListingSourceResult,
    },
};
use application::{
    error::{BoxError, box_error},
    idempotency::{CommandOutcome, field, patch},
};
use listing_source_core::{ListingSourceSlugId, ReferralConfiguration};
use serde_json::{Value, json};

macro_rules! source_result {($ty:ty)=>{impl CommandOutcome for $ty{
    fn encode(&self)->Result<Value,BoxError>{Ok(json!({"listing_source_id":self.listing_source_id,"slug_id":self.slug_id.as_ref()}))}
    fn decode(v:Value)->Result<Self,BoxError>{Ok(Self{listing_source_id:field(&v,"listing_source_id")?,slug_id:ListingSourceSlugId::raw(field::<String>(&v,"slug_id")?).map_err(box_error)?})}
}}}
source_result!(CreateListingSourceResult);
source_result!(UpdateListingSourceResult);

pub(crate) fn operator_value(operator: &ListingSourceOperator) -> Value {
    match operator {
        ListingSourceOperator::Existing(id) => json!({"kind":"EXISTING","id":id}),
        // The ID is generated by transport today; it is preparation, not submitted intent.
        ListingSourceOperator::New(party) => {
            json!({"kind":"NEW","name":party.name.as_ref(),"phone":party.contact.phone,"email":party.contact.email})
        }
    }
}
pub(crate) fn referral_value(value: &ReferralConfiguration) -> Value {
    match value {
        ReferralConfiguration::Partnerize { camref } => {
            json!({"kind":"PARTNERIZE","camref":camref.as_ref()})
        }
    }
}
pub(crate) fn configuration_value(value: &ListingIngestionConfiguration) -> Value {
    match value {
        ListingIngestionConfiguration::WebCrawl { fallback_currency } => {
            json!({"kind":"WEB_CRAWL","currency":fallback_currency.map(|v|v.as_str())})
        }
        ListingIngestionConfiguration::PartnerApi => json!({"kind":"PARTNER_API"}),
        ListingIngestionConfiguration::Shopify {
            domain,
            currency,
            language,
        } => {
            json!({"kind":"SHOPIFY","domain":domain.as_str(),"currency":currency.map(|v|v.as_str()),"language":language.map(|v|v.as_str())})
        }
        // This value exists only during hashing. Only the fingerprint is stored or logged.
        ListingIngestionConfiguration::Woocommerce {
            webhook_secret,
            currency,
            language,
        } => {
            json!({"kind":"WOOCOMMERCE","secret":webhook_secret.as_str(),"currency":currency.map(|v|v.as_str()),"language":language.map(|v|v.as_str())})
        }
    }
}
pub(crate) fn configurations_value(value: &ListingSourceIngestionConfigurations) -> Value {
    let mut values = value.0.iter().map(configuration_value).collect::<Vec<_>>();
    for value in &mut values {
        value.sort_all_objects();
    }
    values.sort_by_key(Value::to_string);
    json!(values)
}
pub(crate) fn updates_value(value: &UpdateListingSourceIngestionConfigurations) -> Value {
    let mut values=value.0.iter().map(|v|match v{
        ListingIngestionConfigurationUpdate::Configuration(v)=>configuration_value(v),
        ListingIngestionConfigurationUpdate::Woocommerce{webhook_secret,currency,language}=>json!({"kind":"WOOCOMMERCE","secret":patch(webhook_secret,|v|json!(v.as_str())),"currency":currency.map(|v|v.as_str()),"language":language.map(|v|v.as_str())}),
    }).collect::<Vec<_>>();
    for value in &mut values {
        value.sort_all_objects();
    }
    values.sort_by_key(Value::to_string);
    json!(values)
}

/// Credential material is hashed immediately and never leaves the owning service as JSON.
pub fn configuration_fingerprint(value: &ListingIngestionConfiguration) -> Vec<u8> {
    let mut value = configuration_value(value);
    value.sort_all_objects();
    application::idempotency::CommandFingerprint::digest(1, value.to_string().as_bytes())
        .as_bytes()
        .to_vec()
}
use crate::use_cases::location_default::{LocationDefaultView, SelectedLocationEligibility};
use listing_source_core::location_default::{
    SourceLocationAssignment, SourceLocationEvidence, SourceLocationMeaning,
};
pub(crate) fn evidence_value(v: &SourceLocationEvidence) -> Value {
    json!({"reference":v.reference(),"scope":v.scope().as_str()})
}
pub(crate) fn assignment_value(v: &SourceLocationAssignment) -> Value {
    json!({"location_id":v.location_id(),"business_association":v.business_association().map(evidence_value),"advertised_inventory":v.advertised_inventory().map(evidence_value)})
}
fn evidence_from(v: Value) -> Result<SourceLocationEvidence, BoxError> {
    SourceLocationEvidence::new(
        field(&v, "reference")?,
        SourceLocationMeaning::from_code(&field::<String>(&v, "scope")?)
            .ok_or_else(|| application::error::static_error("invalid source location meaning"))?,
    )
    .map_err(box_error)
}
impl CommandOutcome for LocationDefaultView {
    fn encode(&self) -> Result<Value, BoxError> {
        Ok(
            json!({"source_id":self.source_id,"revision":self.revision,"assignment":self.assignment.as_ref().map(assignment_value),"eligibility":self.eligibility.map(|v|match v{SelectedLocationEligibility::Active=>"ACTIVE",SelectedLocationEligibility::Retired=>"RETIRED"})}),
        )
    }
    fn decode(v: Value) -> Result<Self, BoxError> {
        Ok(Self {
            source_id: field(&v, "source_id")?,
            revision: field(&v, "revision")?,
            assignment: field::<Option<Value>>(&v, "assignment")?
                .map(|v| {
                    Ok::<_, BoxError>(SourceLocationAssignment::new(
                        field(&v, "location_id")?,
                        field::<Option<Value>>(&v, "business_association")?
                            .map(evidence_from)
                            .transpose()?,
                        field::<Option<Value>>(&v, "advertised_inventory")?
                            .map(evidence_from)
                            .transpose()?,
                    )?)
                })
                .transpose()?,
            eligibility: field::<Option<String>>(&v, "eligibility")?
                .map(|v| match v.as_str() {
                    "ACTIVE" => Ok(SelectedLocationEligibility::Active),
                    "RETIRED" => Ok(SelectedLocationEligibility::Retired),
                    _ => Err(application::error::static_error(
                        "invalid location eligibility",
                    )),
                })
                .transpose()?,
        })
    }
}
