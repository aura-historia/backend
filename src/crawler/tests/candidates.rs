/// Inserts a shop + its first domain; returns the generated domain_id.
async fn insert_shop_with_domain(
    pool: &sqlx::PgPool,
    shop_id_uuid: uuid::Uuid,
    domain: &str,
) -> uuid::Uuid {
    sqlx::query(
        "INSERT INTO shops (shop_id, shop_name, shop_type, created, updated) \
         VALUES ($1, $2, $3, NOW(), NOW())",
    )
    .bind(shop_id_uuid)
    .bind("Test Shop")
    .bind("COMMERCIAL_DEALER")
    .execute(pool)
    .await
    .unwrap();

    insert_domain_for_shop(pool, shop_id_uuid, domain).await
}

/// Inserts an additional domain row for an already-existing shop.
async fn insert_domain_for_shop(
    pool: &sqlx::PgPool,
    shop_id_uuid: uuid::Uuid,
    domain: &str,
) -> uuid::Uuid {
    let row: (uuid::Uuid,) = sqlx::query_as(
        "INSERT INTO shop_domains (shop_id, shop_domain) VALUES ($1, $2) RETURNING domain_id",
    )
    .bind(shop_id_uuid)
    .bind(domain)
    .fetch_one(pool)
    .await
    .unwrap();

    row.0
}

