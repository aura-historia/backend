/// Helper: inserts a product URL into shop_urls for the given shop/domain.
async fn insert_product_url(
    pool: &sqlx::PgPool,
    shop_id_uuid: uuid::Uuid,
    domain_id: uuid::Uuid,
    url: &str,
) {
    let shop_id = shop_core::shop_id::ShopId::from(shop_id_uuid);
    let parsed = url::Url::parse(url).unwrap();
    let repo = UrlMetadataRepositoryImpl::new(pool.clone());
    repo.upsert_link(&shop_id, &domain_id, &parsed, &UrlClass::ProductListing)
        .await
        .unwrap();
}

