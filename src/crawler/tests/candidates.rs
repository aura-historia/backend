#[serial]
#[aura_integration_test(services = [POSTGRES])]
async fn spider_should_order_never_crawled_before_stale_crawled() {
    let pool = get_postgres_client().await;
    let service = SpiderCandidateServiceImpl::new(pool.clone());

    let shop_id_stale = uuid::Uuid::new_v4();
    let shop_id_never = uuid::Uuid::new_v4();

    let domain_id_stale =
        insert_shop_with_domain(&pool, shop_id_stale, "spider-order-stale.example.com").await;
    let domain_id_never =
        insert_shop_with_domain(&pool, shop_id_never, "spider-order-never.example.com").await;

    sqlx::query(
        "UPDATE shop_domains SET last_crawled = NOW() - INTERVAL '10 days' WHERE domain_id = $1",
    )
    .bind(domain_id_stale)
    .execute(&pool)
    .await
    .unwrap();

    let candidates = service.get_candidates(100, &[]).await.unwrap();

    let pos_never = candidates
        .iter()
        .position(|c| c.domain_id == domain_id_never)
        .expect("never-crawled domain should be in candidates");
    let pos_stale = candidates
        .iter()
        .position(|c| c.domain_id == domain_id_stale)
        .expect("stale domain should be in candidates");

    assert!(
        pos_never < pos_stale,
        "never-crawled (pos {pos_never}) should come before stale (pos {pos_stale})"
    );
}

