// ============================================================================
// Real-world classification quality tests
//
// Each test loads the full production category / period data (with the real
// Gemini embeddings stored in the seed JSON), indexes everything into a fresh
// LocalStack OpenSearch instance, and asserts that a hardcoded product-title
// embedding (also generated by Gemini) ranks the correct entry first.
//
// The per-test embedding constants were generated once with
// `MultimodalEmbeddingServiceImpl::embed` and are frozen here so the tests
// run fully offline without any API key.
// ============================================================================

/// Deserialize a `CategoryDocument` from the JSON seed file.
/// The JSON contains real Gemini embeddings so cosine similarity is
/// meaningful against the frozen query embeddings below.
fn load_category_documents_from_data() -> Vec<CategoryDocument> {
    #[derive(serde::Deserialize)]
    #[serde(rename_all = "camelCase")]
    struct CategorySeed {
        category_id: String,
        category_key: String,
        meta_name: String,
        meta_description: String,
        #[serde(default)]
        meta_keywords: Vec<String>,
        embedding: Vec<f32>,
        display_name_de: String,
        display_name_en: String,
        display_name_fr: String,
        display_name_es: String,
        display_name_it: String,
    }

    let raw = include_str!(concat!(
        env!("CARGO_WORKSPACE_DIR"),
        "src/product-classification/data/categories.json"
    ));

    serde_json::from_str::<Vec<CategorySeed>>(raw)
        .expect("failed to parse categories.json")
        .into_iter()
        .map(|s| CategoryDocument {
            category_id: s.category_id.into(),
            category_key: s.category_key.into(),
            meta_name: s.meta_name,
            meta_description: s.meta_description,
            meta_keywords: s.meta_keywords,
            embedding: s.embedding,
            display_name_de: s.display_name_de,
            display_name_en: s.display_name_en,
            display_name_fr: s.display_name_fr,
            display_name_es: s.display_name_es,
            display_name_it: s.display_name_it,
            created: time::OffsetDateTime::now_utc(),
            updated: time::OffsetDateTime::now_utc(),
        })
        .collect()
}

